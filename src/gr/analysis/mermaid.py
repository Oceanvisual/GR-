"""Process flowchart as Mermaid text (api.md § Mermaid-генерация). A pure, deterministic
function: the same process always gives the same text.

`flowchart TD`; operations are boxes «<seq> · <name> — <performer>», decision points are
diamonds, a return for rework is a dotted edge. Operations rejected by the expert are left
out, and the edges through them are bridged so the flow stays connected. Every label is
escaped with Mermaid entity codes: text from the act or the model can neither break the
diagram syntax nor inject markup.
"""

from gr.domain.enums import ReviewStatus
from gr.domain.process import Operation, Process

MAX_LABEL = 80
END_NODE = 'finish(["Завершение процесса"])'
_ENTITIES = {
    "#": "#35;",
    '"': "#quot;",
    "<": "#lt;",
    ">": "#gt;",
    "[": "#91;",
    "]": "#93;",
    "{": "#123;",
    "}": "#125;",
    "(": "#40;",
    ")": "#41;",
    "|": "#124;",
    ";": "#59;",
    "`": "#96;",
    "&": "#38;",
}


def label(text: str, limit: int = MAX_LABEL) -> str:
    """One line, at most `limit` characters, every special character as an entity code."""
    flat = " ".join(text.split())
    if len(flat) > limit:
        flat = flat[: limit - 1].rstrip() + "…"
    return "".join(_ENTITIES.get(char, char) for char in flat)


def _node(element_id: str) -> str:
    """`proc_1.op_3` → `op_3`; ids are generated by the validator, never by the model."""
    return element_id.rsplit(".", 1)[-1]


def _operation_label(operation: Operation) -> str:
    performer = operation.performer.value if operation.performer else "исполнитель не указан"
    # «1 ·», not «1.»: Mermaid reads a label that starts like «1. » as a Markdown list.
    return label(f"{operation.seq + 1} · {operation.name} — {performer}")


def process_to_mermaid(process: Process) -> str:
    rejected = {op.id for op in process.operations if op.review.status == ReviewStatus.REJECTED}
    shown = [op for op in process.operations if op.id not in rejected]
    by_id = {op.id: op for op in process.operations}

    def prerequisites(operation: Operation, seen: frozenset[str] = frozenset()) -> list[str]:
        """Dependencies, a rejected one replaced by its own (the flow stays connected)."""
        result: list[str] = []
        for dependency in operation.depends_on:
            if dependency in rejected and dependency not in seen:
                result += prerequisites(by_id[dependency], seen | {dependency})
            elif dependency in by_id and dependency not in rejected:
                result.append(dependency)
        return list(dict.fromkeys(result))

    lines = ["flowchart TD"]
    for op in shown:
        lines.append(f'    {_node(op.id)}["{_operation_label(op)}"]')
    points = [dp for dp in process.decision_points if dp.after_operation_id not in rejected]
    for dp in points:
        lines.append(f'    {_node(dp.id)}{{"{label(dp.condition.value)}"}}')
    if any(o.ends_process for dp in points for o in dp.outcomes):
        lines.append(f"    {END_NODE}")

    # An operation reached through a decision does not need the direct edge from the step
    # the decision follows: the path through the diamond already shows it.
    via_decision = {
        (dp.after_operation_id, outcome.next_operation_id)
        for dp in points
        for outcome in dp.outcomes
        if outcome.next_operation_id
    }
    edges: list[str] = []
    for op in shown:
        for dependency in prerequisites(op):
            if (dependency, op.id) in via_decision:
                continue
            arrow = "-.->" if by_id[dependency].is_loop_back else "-->"
            edges.append(f"    {_node(dependency)} {arrow} {_node(op.id)}")
    for dp in points:
        edges.append(f"    {_node(dp.after_operation_id)} --> {_node(dp.id)}")
        for outcome in dp.outcomes:
            if outcome.next_operation_id and outcome.next_operation_id not in rejected:
                target = _node(outcome.next_operation_id)
            elif outcome.ends_process:
                target = "finish"
            else:
                continue
            edges.append(f'    {_node(dp.id)} -- "{label(outcome.label, 40)}" --> {target}')
    lines += list(dict.fromkeys(edges))
    return "\n".join(lines) + "\n"
